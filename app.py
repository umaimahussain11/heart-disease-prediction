import streamlit as st
import pandas as pd
import joblib

# -----------------------------
# Load trained model
# -----------------------------
model = joblib.load("heart_disease_model.pkl")

# -----------------------------
# Page configuration
# -----------------------------
st.set_page_config(
    page_title="Heart Disease Prediction",
    page_icon="❤️",
    layout="centered"
)

# -----------------------------
# Title
# -----------------------------
st.title("❤️ Heart Disease Risk Prediction")

st.write(
    "Enter the patient information below to estimate the likelihood "
    "of heart disease using a trained machine learning model."
)

st.info(
    "⚠️ This application is an educational machine-learning project "
    "and is NOT a medical diagnosis tool."
)

st.divider()

# -----------------------------
# Patient Information
# -----------------------------
st.subheader("👤 Patient Information")

col1, col2 = st.columns(2)

with col1:
    age = st.number_input(
        "Age",
        min_value=1,
        max_value=100,
        value=50
    )

with col2:
    sex = st.selectbox(
        "Sex",
        options=[0, 1],
        format_func=lambda x: "Female" if x == 0 else "Male"
    )

# -----------------------------
# Medical Information
# -----------------------------
st.subheader("🩺 Medical Information")

cp = st.selectbox(
    "Chest Pain Type",
    options=[1, 2, 3, 4],
    format_func=lambda x: {
        1: "Type 1",
        2: "Type 2",
        3: "Type 3",
        4: "Type 4"
    }[x]
)

col1, col2 = st.columns(2)

with col1:
    trestbps = st.number_input(
        "Resting Blood Pressure",
        min_value=80,
        max_value=250,
        value=120
    )

with col2:
    chol = st.number_input(
        "Cholesterol",
        min_value=100,
        max_value=600,
        value=200
    )

fbs = st.selectbox(
    "Fasting Blood Sugar > 120 mg/dl",
    options=[0, 1],
    format_func=lambda x: "No" if x == 0 else "Yes"
)

restecg = st.selectbox(
    "Resting ECG Result",
    options=[0, 1, 2]
)

thalach = st.number_input(
    "Maximum Heart Rate Achieved",
    min_value=60,
    max_value=250,
    value=150
)

exang = st.selectbox(
    "Exercise-Induced Angina",
    options=[0, 1],
    format_func=lambda x: "No" if x == 0 else "Yes"
)

oldpeak = st.number_input(
    "ST Depression (oldpeak)",
    min_value=0.0,
    max_value=10.0,
    value=1.0,
    step=0.1
)

slope = st.selectbox(
    "Slope",
    options=[1, 2, 3]
)

ca = st.selectbox(
    "Number of Major Vessels (ca)",
    options=[0, 1, 2, 3]
)

thal = st.selectbox(
    "Thal",
    options=[3, 6, 7]
)

st.divider()

# -----------------------------
# Prediction
# -----------------------------
if st.button("🔍 Predict Heart Disease Risk", use_container_width=True):

    input_data = pd.DataFrame({
        "age": [age],
        "sex": [sex],
        "cp": [cp],
        "trestbps": [trestbps],
        "chol": [chol],
        "fbs": [fbs],
        "restecg": [restecg],
        "thalach": [thalach],
        "exang": [exang],
        "oldpeak": [oldpeak],
        "slope": [slope],
        "ca": [ca],
        "thal": [thal]
    })

    # Make prediction
    prediction = model.predict(input_data)[0]

    # Probability of positive class
    probability = model.predict_proba(input_data)[0][1]

    st.subheader("📊 Prediction Result")

    if prediction == 1:
        st.warning(
            "⚠️ The model predicts a higher likelihood of heart disease."
        )
    else:
        st.success(
            "✅ The model predicts a lower likelihood of heart disease."
        )

    st.write(
        f"Estimated model probability for the positive class: "
        f"**{probability * 100:.2f}%**"
    )

    # Visual probability bar
    st.progress(
        float(probability),
        text=f"Model probability: {probability * 100:.2f}%"
    )

    st.caption(
        "This prediction is generated by a machine-learning model "
        "and should not be used as medical advice."
    )